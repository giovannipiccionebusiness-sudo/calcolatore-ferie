import assert from 'node:assert/strict';
import {validateResult,RESULT_SCHEMA,normalizeMonth} from '../supabase/functions/attendance-ai/attendance-ai-result.js';
const row={day:2,total_minutes:420,absence_minutes:null,cause:'',uncertain:false};
const sample={month:'2026-10',worker_name:'Esempio',monthly_total_minutes:420,rows:[row]};
assert.equal(validateResult(sample,'2026-10').rows[0].total_minutes,420);
assert.equal(validateResult({...sample,rows:[{...row,total_minutes:null,uncertain:true}]},'2026-10').rows[0].total_minutes,null);
for(const rows of [[],[row,row],[{...row,total_minutes:-1}],[{...row,total_minutes:1441}],[{...row,cause:'unknown'}],[{...row,day:31,total_minutes:60}]])assert.throws(()=>validateResult({...sample,rows},'2026-02'));
assert.equal(RESULT_SCHEMA.additionalProperties,false);
for(const value of ['2026-10','10.2026','10/2026','ottobre 2026','2026/10','2026-10-01'])assert.equal(normalizeMonth(value),'2026-10');
assert.equal(normalizeMonth('novembre 2026'),'2026-11');
assert.equal(normalizeMonth('non leggibile'),null);
assert.equal(normalizeMonth('10/26'),null);
assert.equal(validateResult({...sample,month:'10.2026'},'2026-10').month,'2026-10');
assert.equal(validateResult({...sample,month:'illeggibile'},'2026-10').month,null);
console.log('AI result validation: nulls, invalid hours, duplicate days and month boundaries passed');
const {sheetMinutes}=await import('../supabase/functions/attendance-ai/attendance-ai-result.js');
for(const text of ['3,40','3.40','3:40'])assert.equal(sheetMinutes(text),220);
assert.equal(sheetMinutes('5,30'),330);assert.equal(sheetMinutes('3,60'),null);
assert.equal(sheetMinutes('3,4'),null);assert.equal(sheetMinutes('100,40',44640),6040);
const raw=validateResult({...sample,monthly_total_text:'3,40',rows:[{...row,total_text:'3,40',absence_text:null,total_minutes:180}]},'2026-10');
assert.equal(raw.rows[0].total_minutes,220);assert.equal(raw.monthly_total_minutes,220);
const {decimalMinutes,splitWorked}=await import('../attendance-reader-core.js');
assert.equal(decimalMinutes('3,67'),220);assert.equal(decimalMinutes('0,67'),40);
const split=splitWorked(220,180);assert.equal(split.ordinary,180);assert.equal(split.supplementary,40);
console.log('Paper 3,40 -> 220 exact minutes -> app 3,67; O 3,00 / S 0,67 passed');

assert.equal(sheetMinutes('6 20'),380);assert.equal(sheetMinutes('5 60'),null);
